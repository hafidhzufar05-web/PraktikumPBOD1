    // Method pembantu untuk mengambil data dari DB dan menampilkannya ke tabel
    private void tampilkanData() {
        tableModel.setRowCount(0); // Kosongkan tabel dulu
        java.util.List<jdbc.model.Mahasiswa> list = service.getAll();
        for (jdbc.model.Mahasiswa mhs : list) {
            tableModel.addRow(new Object[]{
                mhs.getId(),
                mhs.getNama()
            });
        }
    }
