    private void jButtonTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonTambahActionPerformed
        // TODO add your handling code here:
        String nama = jTextFieldNama.getText();
    if (!nama.isEmpty()) {
        jdbc.model.Mahasiswa mhs = new jdbc.model.Mahasiswa();
        mhs.setNama(nama);
        service.add(mhs);
        
        jTextFieldNama.setText(""); // Kosongkan kolom input
        tampilkanData(); // Refresh tabel
    }
    }//GEN-LAST:event_jButtonTambahActionPerformed

    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
        // TODO add your handling code here:
        try {
        int id = Integer.parseInt(jTextFieldIdEdit.getText());
        String namaBaru = jTextFieldNamaEdit.getText(); 
        
        if (!namaBaru.isEmpty()) {
            jdbc.model.Mahasiswa mhs = new jdbc.model.Mahasiswa();
            mhs.setId(id);
            mhs.setNama(namaBaru);
            service.update(mhs);
            
            jTextFieldIdEdit.setText("");
            jTextFieldNamaEdit.setText("");
            tampilkanData();
        }
    } catch (NumberFormatException e) {
        System.out.println("Error: ID harus angka!");
    }
    }//GEN-LAST:event_jButtonEditActionPerformed

    private void jButtonHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonHapusActionPerformed
        // TODO add your handling code here:
        try {
        int id = Integer.parseInt(jTextFieldIdHapus.getText());
        service.delete(id);
        
        jTextFieldIdHapus.setText("");
        jTextFieldNamaHapus.setText("");
        tampilkanData();
    } catch (NumberFormatException e) {
        System.out.println("Error: ID harus angka!");
    }
    }//GEN-LAST:event_jButtonHapusActionPerformed

